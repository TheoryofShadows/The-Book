/* Registers the service worker, and tells the reader when the network is
   gone.
 *
 * Loaded from the <head> of docs/index.html rather than from the body, and
 * that is load-bearing rather than tidy: tools/build_standalone.py keeps only
 * the body of that page and writes its own head, so a tag in the head is
 * dropped from the single-file copy. Which is what should happen. The offline
 * copy is opened from file://, where there is no service worker to register
 * and no network to lose, and a registration running there would be an error
 * thrown on every open of the one build that has no console to see it in.
 *
 * The worker itself is docs/sw.js, generated by tools/build_sw.py.
 */

(function () {
  "use strict";

  /* Not every browser has one, and none of them do over plain http from
     somewhere that is not localhost. Both are ordinary rather than
     exceptional, so neither is an error worth showing anybody. */
  if (!("serviceWorker" in navigator)) return;

  window.addEventListener("load", function () {
    navigator.serviceWorker.register("sw.js", { scope: "./" })
      .catch(function () {
        /* A failed registration costs the offline copy and nothing else: the
           site is static files and works exactly as it did before. Silent on
           purpose -- there is nothing here a reader could act on. */
      });
  });

  /* ---------------- saying so ----------------

     A cache that answers when the network cannot is only honest if the page
     admits which one it is talking to. Without this the reader looks
     identical online and off, and "identical" is a claim that what is on
     screen is current -- which, in a tunnel, it is not.

     navigator.onLine is a coarse signal: it reports the machine's own idea
     of having a connection, and a captive portal or a dead uplink can leave
     it true with nothing reachable. It is right about the case this is for,
     which is a phone that has plainly lost signal, and it is the only signal
     available without inventing traffic to test with. So the wording is
     "may be" rather than "is": it says what is known and not more. */

  var note = null;

  function show() {
    if (note) return;
    note = document.createElement("p");
    note.className = "offline-note";
    /* polite rather than assertive: this interrupts nothing, and a reader
       part-way through a verse should hear it at the end of the sentence. */
    note.setAttribute("role", "status");
    note.setAttribute("aria-live", "polite");
    note.textContent = "Offline. What is on screen is the last copy this "
      + "device fetched, and may not be current.";
    document.body.appendChild(note);
  }

  function hide() {
    if (!note) return;
    note.remove();
    note = null;
  }

  window.addEventListener("offline", show);
  window.addEventListener("online", hide);

  /* The page can be opened already offline, in which case no event ever
     fires and the banner would never appear. */
  if (navigator.onLine === false) {
    if (document.body) show();
    else window.addEventListener("DOMContentLoaded", show);
  }
})();
